"""Generate sql/03_features.sql (per-readout features, no look-ahead).

The SQL is generated because the histograms have 10-36 bins each and hand-writing every
bin sum is error-prone. Edit this script, not the .sql file, then run:
    python src/make_features_sql.py
build_dataset.py runs the generated file like any other sql/*.sql.
"""

from __future__ import annotations

from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "sql" / "03_features.sql"

COUNTERS = ["171", "666", "427", "837", "309", "835", "370", "100"]
HISTOGRAMS = {"167": 10, "272": 10, "291": 11, "158": 10, "459": 20, "397": 36}


def q(name: str) -> str:
    return f'"{name}"'


def build() -> str:
    L: list[str] = []
    add = L.append
    add("-- 03_features.sql: one row of features per readout, all splits -> readout_features.")
    add("-- GENERATED by src/make_features_sql.py -- edit that script, not this file.")
    add("--")
    add("-- No look-ahead: every window is PARTITION BY split, vehicle_id ORDER BY time_step and")
    add("-- reaches only backwards (lag, or ROWS BETWEEN 4 PRECEDING AND CURRENT ROW). There is")
    add("-- no FOLLOWING, lead() or whole-partition aggregate, so a feature at readout t uses only")
    add("-- readouts at or before t. tests/test_no_lookahead.py proves this by truncation.")
    add("--")
    add("-- 'Last 5 readouts' = the current readout and the 4 before it. Vehicles with fewer than")
    add("-- 5 readouts so far use what exists; readouts_so_far tells the model how much history")
    add("-- there was. Features at a vehicle's first readout that need a previous one are NULL.")
    add("-- Counters and histograms are cumulative (they decrease in < 0.5% of consecutive")
    add("-- readouts; kept as is), so changes and rates carry the recent signal.")
    add("-- Only reads table `readouts`.")
    add("")
    add("CREATE OR REPLACE TABLE readout_features AS")
    add("WITH base AS (")
    add("    -- Per readout: counter levels and three linear histogram aggregates")
    add("    -- (total count, bin-index-weighted sum, count in the top 2 bins). Missing bins count as 0.")
    sel = ["        split", "        vehicle_id", "        time_step"]
    for c in COUNTERS:
        sel.append(f"        {q(c + '_0')} AS c{c}")
    for h, n in HISTOGRAMS.items():
        bins = [f"coalesce({q(f'{h}_{i}')}, 0)" for i in range(n)]
        sel.append(f"        ({' + '.join(bins)}) AS h{h}_total")
        weighted = [f"{i} * coalesce({q(f'{h}_{i}')}, 0)" for i in range(1, n)]
        sel.append(f"        ({' + '.join(weighted)}) AS h{h}_wsum")
        sel.append(f"        (coalesce({q(f'{h}_{n - 2}')}, 0) + coalesce({q(f'{h}_{n - 1}')}, 0)) AS h{h}_top2")
    add("    SELECT\n" + ",\n".join(sel))
    add("    FROM readouts")
    add("),")
    add("win AS (")
    add("    -- Backward-looking window values: previous readout (lag) and the oldest readout in")
    add("    -- the 5-readout window (first_value over w5).")
    sel = ["        *",
           "        row_number() OVER w AS readouts_so_far",
           "        lag(time_step) OVER w AS ts_prev",
           "        first_value(time_step) OVER w5 AS ts_5"]
    for c in COUNTERS:
        sel.append(f"        lag(c{c}) OVER w AS c{c}_prev")
        sel.append(f"        first_value(c{c}) OVER w5 AS c{c}_5")
    for h in HISTOGRAMS:
        for part in ("total", "wsum", "top2"):
            sel.append(f"        first_value(h{h}_{part}) OVER w5 AS h{h}_{part}_5")
    add("    SELECT\n" + ",\n".join(sel))
    add("    FROM base")
    add("    WINDOW w  AS (PARTITION BY split, vehicle_id ORDER BY time_step),")
    add("           w5 AS (PARTITION BY split, vehicle_id ORDER BY time_step ROWS BETWEEN 4 PRECEDING AND CURRENT ROW)")
    add(")")
    add("SELECT")
    out = ["    split", "    vehicle_id",
           "",
           "    -- Timing: operating time, history length, gap since the previous readout and",
           "    -- span of the last 5 readouts (readouts are irregular, so rates divide by these).",
           "    time_step",
           "    readouts_so_far",
           "    time_step - ts_prev AS dt_prev",
           "    nullif(time_step - ts_5, 0) AS dt_last5",
           "",
           "    -- Counter levels: raw cumulative values (lifetime usage)."]
    out += [f"    c{c} AS c{c}_level" for c in COUNTERS]
    out += ["", "    -- Counter change since the previous readout, and per time step."]
    for c in COUNTERS:
        out.append(f"    c{c} - c{c}_prev AS c{c}_delta_prev")
        out.append(f"    (c{c} - c{c}_prev) / nullif(time_step - ts_prev, 0) AS c{c}_rate_prev")
    out += ["", "    -- Counter change over the last 5 readouts, and per time step (recent usage intensity)."]
    for c in COUNTERS:
        # NULL (not 0) at the first readout, where the window holds only the readout itself.
        out.append(f"    CASE WHEN readouts_so_far > 1 THEN c{c} - c{c}_5 END AS c{c}_delta_5")
        out.append(f"    (c{c} - c{c}_5) / nullif(time_step - ts_5, 0) AS c{c}_rate_5")
    out += ["",
            "    -- Histogram lifetime summaries (cumulative histogram): total count, weighted mean",
            "    -- bin index (0 = lowest bin), share in the top 2 bins, and change in mean bin over",
            "    -- the last 5 readouts. These move slowly because the histogram is cumulative."]
    for h in HISTOGRAMS:
        mean_now = f"h{h}_wsum / nullif(h{h}_total, 0)"
        mean_5 = f"h{h}_wsum_5 / nullif(h{h}_total_5, 0)"
        out.append(f"    h{h}_total")
        out.append(f"    {mean_now} AS h{h}_mean_bin")
        out.append(f"    h{h}_top2 / nullif(h{h}_total, 0) AS h{h}_top2_share")
        out.append(f"    CASE WHEN readouts_so_far > 1 THEN {mean_now} - {mean_5} END AS h{h}_mean_bin_change_5")
    out += ["",
            "    -- Histogram recent-window summaries: the same summaries on the histogram INCREMENT",
            "    -- over the last 5 readouts (now minus 4 readouts back), i.e. how the vehicle was used",
            "    -- recently rather than over its whole life. NULL when the increment total is <= 0",
            "    -- (first readout, or a rare decrease in the cumulative counts)."]
    for h in HISTOGRAMS:
        inc_total = f"(h{h}_total - h{h}_total_5)"
        guard = f"CASE WHEN {inc_total} > 0 THEN {inc_total} END"
        out.append(f"    (h{h}_wsum - h{h}_wsum_5) / {guard} AS h{h}_recent5_mean_bin")
        out.append(f"    (h{h}_top2 - h{h}_top2_5) / {guard} AS h{h}_recent5_top2_share")
    # join with commas, keeping blank/comment lines comma-free
    rendered, items = [], [o for o in out]
    last_expr = max(i for i, o in enumerate(items) if o and not o.lstrip().startswith("--"))
    for i, o in enumerate(items):
        is_expr = o and not o.lstrip().startswith("--")
        rendered.append(o + ("," if is_expr and i != last_expr else ""))
    add("\n".join(rendered))
    add("FROM win")
    add("ORDER BY split, vehicle_id, time_step;")
    return "\n".join(L) + "\n"


FEATURE_GROUPS = {
    "timing": ["time_step", "readouts_so_far", "dt_prev", "dt_last5"],
    "counter_level": [f"c{c}_level" for c in COUNTERS],
    "counter_prev": [f"c{c}_{k}" for c in COUNTERS for k in ("delta_prev", "rate_prev")],
    "counter_last5": [f"c{c}_{k}" for c in COUNTERS for k in ("delta_5", "rate_5")],
    "hist_lifetime": [f"h{h}_{k}" for h in HISTOGRAMS for k in ("total", "mean_bin", "top2_share", "mean_bin_change_5")],
    "hist_recent5": [f"h{h}_{k}" for h in HISTOGRAMS for k in ("recent5_mean_bin", "recent5_top2_share")],
}
FEATURES = [f for group in FEATURE_GROUPS.values() for f in group]

if __name__ == "__main__":
    OUT.write_text(build(), encoding="utf-8")
    print(f"wrote {OUT} ({len(FEATURES)} features)")
